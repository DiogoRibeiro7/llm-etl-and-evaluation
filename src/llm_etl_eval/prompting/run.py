"""CLI for generating prompt payloads from inputs."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from llm_etl_eval.config import PipelineConfig, load_config
from llm_etl_eval.prompting.builder import build_prompt_payload


def _load_jsonl(path: Path) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        records.append(json.loads(line))
    return records


def _load_schema(path: Path | None) -> str | None:
    if path is None:
        return None
    schema = json.loads(path.read_text(encoding="utf-8"))
    return json.dumps(schema, sort_keys=True)


def _load_config(path: Path | None) -> PipelineConfig:
    if path is None:
        return PipelineConfig()
    return load_config(path)


def _write_jsonl(records: list[dict[str, Any]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, sort_keys=True) + "\n")


def run_prompting(
    inputs_path: Path,
    out_path: Path,
    schema_path: Path | None = None,
    config_path: Path | None = None,
) -> None:
    """Generate prompt payloads for each input record."""

    config = _load_config(config_path)
    schema_json = _load_schema(schema_path) if config.schema_reminders else None
    records = _load_jsonl(inputs_path)

    prompts: list[dict[str, Any]] = []
    for record in records:
        payload = build_prompt_payload(
            record,
            strictness=config.prompt_strictness,
            schema_reminders=config.schema_reminders,
            schema_json=schema_json,
        )
        prompts.append({"system": payload.system, "user": payload.user})

    _write_jsonl(prompts, out_path)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="llm-etl-eval-prompting",
        description="Generate prompt payloads for LLM calls.",
    )
    parser.add_argument(
        "--inputs",
        type=Path,
        required=True,
        help="Path to llm_inputs.jsonl generated by ETL.",
    )
    parser.add_argument(
        "--out",
        type=Path,
        required=True,
        help="Output JSONL file for prompt payloads.",
    )
    parser.add_argument(
        "--schema",
        type=Path,
        required=False,
        help="Optional schema to embed as a reminder.",
    )
    parser.add_argument(
        "--config",
        type=Path,
        required=False,
        help="Optional pipeline config (YAML/JSON) for prompt strictness.",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    run_prompting(args.inputs, args.out, args.schema, args.config)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
