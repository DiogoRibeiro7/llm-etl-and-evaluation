"""CLI for running the LLM output simulator."""

from __future__ import annotations

import argparse
from pathlib import Path

from llm_etl_eval.sim.llm_simulator import SimulationConfig, load_inputs, simulate_records, write_outputs


def build_parser() -> argparse.ArgumentParser:
    """Build the CLI argument parser."""

    parser = argparse.ArgumentParser(
        prog="llm-etl-eval-sim",
        description="Simulate LLM outputs with controlled error modes.",
    )
    parser.add_argument(
        "--inputs",
        type=Path,
        required=True,
        help="Path to llm_inputs.jsonl generated by the ETL pipeline.",
    )
    parser.add_argument(
        "--outputs",
        type=Path,
        required=True,
        help="Path to write simulated outputs JSONL.",
    )
    parser.add_argument(
        "--error-rate",
        type=float,
        default=0.2,
        help="Probability of generating an invalid output.",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=7,
        help="Random seed for deterministic outputs.",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""

    parser = build_parser()
    args = parser.parse_args(argv)

    config = SimulationConfig(error_rate=args.error_rate, seed=args.seed)
    records = load_inputs(args.inputs)
    results = simulate_records(records, config)
    write_outputs(results, args.outputs)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
